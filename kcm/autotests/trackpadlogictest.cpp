QByteArray readAll(const QString &path)
{
    QFile f(path);
    if (!f.open(QIODevice::ReadOnly)) {
        return {};
    }
    return f.readAll();
}

bool writeAll(const QString &path, const QByteArray &data)
{
    QFile f(path);
    return f.open(QIODevice::WriteOnly | QIODevice::Truncate) && f.write(data) == data.size();
}

mode_t fileMode(const QString &path)
{
    struct stat st;
    return ::stat(QFile::encodeName(path).constData(), &st) == 0 ? (st.st_mode & 07777) : 0;
}

ino_t fileInode(const QString &path)
{
    struct stat st;
    return ::stat(QFile::encodeName(path).constData(), &st) == 0 ? st.st_ino : 0;
}

QProcessEnvironment envOf(std::initializer_list<std::pair<QString, QString>> vars)
{
    QProcessEnvironment env;
    for (const auto &[k, v] : vars) {
        env.insert(k, v);
    }
    return env;
}
