"""Tests for the Qt Backend (no QML, no display): nothing is written until a
control moves, and what is written leaves hidden values alone.

Never touches the real config: MAC_TRACKPAD_CONFIG_DIR points at a temp dir.
"""
import json
import os
import stat
import sys
import tempfile
import unittest

APP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, APP)

try:
    from PyQt6.QtCore import QCoreApplication
    from mac_trackpad_settings.backend import Backend
except ImportError:  # pragma: no cover
    Backend = None

HEADER = """# generated by mac_curves.py: pointer setting 1.2, scroll setting 0.4412,
# res 52.5 units/mm, pointer gain 1.75, scroll gain 0.6,
# kwin scroll factor 2.2
motion_step=0.3
"""


@unittest.skipIf(Backend is None, "PyQt6 not installed")
class BackendTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.app = QCoreApplication.instance() or QCoreApplication([])

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.dir = os.path.join(self.tmp.name, "mac-trackpad")
        os.makedirs(self.dir)
        self.daemon = os.path.join(self.dir, "daemon.json")
        self.accel = os.path.join(self.dir, "accel.conf")
        self.log = os.path.join(self.tmp.name, "args.log")
        tool = os.path.join(self.tmp.name, "fake-accel")
        with open(tool, "w") as f:
            f.write('#!/bin/sh\necho "$@" >> "%s"\n' % self.log)
        os.chmod(tool, 0o755)
        self.saved = {k: os.environ.get(k) for k in
                      ("MAC_TRACKPAD_CONFIG_DIR", "MAC_TRACKPAD_ACCEL", "XDG_CURRENT_DESKTOP",
                       "HYPRLAND_INSTANCE_SIGNATURE")}
        os.environ["XDG_CURRENT_DESKTOP"] = "KDE"
        # a Hyprland session running the tests would count as Hyprland
        os.environ.pop("HYPRLAND_INSTANCE_SIGNATURE", None)
        os.environ["MAC_TRACKPAD_CONFIG_DIR"] = self.dir
        os.environ["MAC_TRACKPAD_ACCEL"] = tool

    def tearDown(self):
        for k, v in self.saved.items():
            if v is None:
                os.environ.pop(k, None)
            else:
                os.environ[k] = v
        self.tmp.cleanup()

    def write(self, path, text):
        with open(path, "w") as f:
            f.write(text)

    def test_off_list_values_shown_and_nothing_written(self):
        daemon = '{"momentum": false, "momentumFastDecay": 0.97}\n'
        self.write(self.daemon, daemon)
        self.write(self.accel, HEADER)
        b = Backend()
        self.assertEqual(b.pointerPosition, 5)         # 1.2 -> 1
        self.assertEqual(b.scrollPosition, 5)          # 0.4412
        self.assertIs(b.momentum, False)
        self.assertFalse(b._mtimer.isActive() or b._ctimer.isActive())
        b.flush()
        with open(self.daemon) as f:
            self.assertEqual(f.read(), daemon)
        self.assertFalse(os.path.exists(self.log))

    def test_momentum_writes_only_that_key(self):
        before = {"momentum": True, "momentumFastDecay": 0.97, "momentumStopHold": 160, "x": [1]}
        self.write(self.daemon, json.dumps(before))
        os.chmod(self.daemon, 0o600)
        b = Backend()
        b.setMomentum(False)
        b.flush()
        with open(self.daemon) as f:
            self.assertEqual(json.load(f), dict(before, momentum=False))
        self.assertEqual(stat.S_IMODE(os.stat(self.daemon).st_mode), 0o600)
        self.assertFalse(os.path.exists(self.log), "inertia must not run mac-trackpad-accel")

    def test_drag_writes_only_that_key(self):
        before = {"momentum": False, "momentumFastDecay": 0.97, "x": [1]}
        self.write(self.daemon, json.dumps(before))
        b = Backend()
        self.assertIs(b.threeFingerDrag, False)
        b.setThreeFingerDrag(True)
        b.flush()
        with open(self.daemon) as f:
            self.assertEqual(json.load(f), dict(before, threeFingerDrag=True))

    def test_speed_keeps_hidden_accel_values(self):
        self.write(self.accel, HEADER)
        b = Backend()
        b.setScrollPosition(7)                          # 1
        b.setPointerPosition(7)                         # 2
        self.assertEqual(b.pointerPosition, 7)
        b._apply_curve()                                # what the debounce timer runs
        for _ in range(200):
            self.app.processEvents()
            if b._proc is None:
                break
            b._proc.waitForFinished(50)
        with open(self.log) as f:
            self.assertEqual(f.read().split(), (
                "set --pointer-setting 2 --pointer-gain 1.75 --scroll-setting 1 "
                "--scroll-gain 0.6 --kwin-scroll-factor 2.2 --res 52.5 --step 0.3").split())

    def test_missing_accel_conf_uses_defaults(self):
        b = Backend()
        self.assertEqual(b.pointerPosition, 6)          # 1.5
        self.assertEqual(b.scrollPosition, 4)          # 0.3125
        self.assertEqual(b._set_args()[0:3], ["set", "--pointer-setting", "1.5"])
        self.assertIn("--res 47 --step 0.25", " ".join(b._set_args()))

    def test_speeds_available_on_kde_and_hyprland_only(self):
        self.assertIs(Backend().speedsAvailable, True)
        os.environ["XDG_CURRENT_DESKTOP"] = "Hyprland"
        self.assertIs(Backend().speedsAvailable, True)
        os.environ["XDG_CURRENT_DESKTOP"] = "ubuntu:GNOME"
        self.assertIs(Backend().speedsAvailable, False)
        os.environ["HYPRLAND_INSTANCE_SIGNATURE"] = "abc"
        self.assertIs(Backend().speedsAvailable, True)

    def test_speeds_unavailable_writes_and_runs_nothing(self):
        os.environ["XDG_CURRENT_DESKTOP"] = "GNOME"
        self.write(self.accel, HEADER)
        b = Backend()
        self.assertIs(b.speedsAvailable, False)
        self.assertEqual((b.pointerPosition, b.scrollPosition), (5, 5))   # stored values still shown
        self.assertFalse(b.statusError)
        b.setPointerPosition(0)
        b.setScrollPosition(0)
        self.assertEqual((b.pointerPosition, b.scrollPosition), (5, 5))
        self.assertFalse(b._ctimer.isActive())
        b._apply_curve()                                # even if something calls it
        b.flush()
        self.assertIsNone(b._proc)
        self.assertFalse(os.path.exists(self.log), "no mac-trackpad-accel off KDE")
        with open(self.accel) as f:
            self.assertEqual(f.read(), HEADER)
        self.assertFalse(os.path.exists(self.daemon))

    def test_speeds_unavailable_no_accel_files_is_not_an_error(self):
        os.environ["XDG_CURRENT_DESKTOP"] = "GNOME"
        os.environ["MAC_TRACKPAD_ACCEL"] = os.path.join(self.tmp.name, "missing-tool")
        b = Backend()
        self.assertFalse(b.statusError)
        self.assertEqual(b.status, "Ready")

    def test_switches_work_without_speeds(self):
        os.environ["XDG_CURRENT_DESKTOP"] = "GNOME"
        os.environ["MAC_TRACKPAD_ACCEL"] = os.path.join(self.tmp.name, "missing-tool")
        before = {"momentum": True, "threeFingerDrag": True, "x": [1]}
        self.write(self.daemon, json.dumps(before))
        b = Backend()
        b.setMomentum(False)
        b.setThreeFingerDrag(False)
        b.flush()
        with open(self.daemon) as f:
            self.assertEqual(json.load(f), dict(before, momentum=False, threeFingerDrag=False))
        self.assertFalse(b.statusError)
        self.assertFalse(os.path.exists(self.log))

    def test_kde_without_accel_tool_keeps_status_error(self):
        os.environ["MAC_TRACKPAD_ACCEL"] = os.path.join(self.tmp.name, "missing-tool")
        b = Backend()
        b.setPointerPosition(0)
        b._apply_curve()
        self.assertTrue(b.statusError)
        self.assertIn("mac-trackpad-accel not found", b.status)

    def test_kde_switches_do_not_need_accel_tool(self):
        os.environ["MAC_TRACKPAD_ACCEL"] = os.path.join(self.tmp.name, "missing-tool")
        b = Backend()
        b.setMomentum(False)
        b.flush()
        with open(self.daemon) as f:
            self.assertEqual(json.load(f)["momentum"], False)


if __name__ == "__main__":
    unittest.main()
