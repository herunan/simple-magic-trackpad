"""The Omarchy panel's omarchy/Model.js against core.py, under node.

The panel can't run here (it needs the Omarchy shell), but its logic is
plain JavaScript: this runs it in node and checks it gives the same answers
as the Python app's core for the same inputs. Skipped without node.
"""
import json
import os
import shutil
import subprocess
import sys
import unittest

APP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = os.path.dirname(APP)
MODEL = os.path.join(REPO, "omarchy", "Model.js")
sys.path.insert(0, APP)
from mac_trackpad_settings import core  # noqa: E402

# Loads Model.js the way QML does (top-level functions and vars), calls
# each [name, args] from stdin and prints the results as JSON.
RUNNER = r"""
const fs = require('fs'), vm = require('vm')
const ctx = vm.createContext({})
vm.runInContext(fs.readFileSync(process.argv[1], 'utf8'), ctx)
const calls = JSON.parse(fs.readFileSync(0, 'utf8'))
const out = calls.map(([name, args]) => {
  const v = vm.runInContext(name, ctx)
  return typeof v === 'function' ? v(...args) : v
})
process.stdout.write(JSON.stringify(out))
"""

HEADER = """# generated by mac_curves.py: pointer setting 1.2, scroll setting 0.4412,
# res 52.5 units/mm, pointer gain 1.75, scroll gain 0.6,
# kwin scroll factor 2.2
motion_step=0.3
motion_points=0.0000 0.1
"""


@unittest.skipIf(shutil.which("node") is None, "node not installed")
class ModelParityTest(unittest.TestCase):
    def js(self, *calls):
        r = subprocess.run(["node", "-e", RUNNER, MODEL], input=json.dumps(calls),
                           capture_output=True, text=True, timeout=60)
        self.assertEqual(r.returncode, 0, r.stderr)
        return json.loads(r.stdout)

    def test_positions(self):
        pointer, scroll = self.js(["POINTER_POSITIONS", []], ["SCROLL_POSITIONS", []])
        self.assertEqual(pointer, list(core.POINTER_POSITIONS))
        self.assertEqual(scroll, list(core.SCROLL_POSITIONS))
        self.assertEqual(len(pointer), 10)
        self.assertEqual(len(scroll), 8)

    def test_nearest_position_matches(self):
        values = [-1, 0, 0.06, 0.0625, 0.07, 0.3, 0.3125, 0.6, 1.2, 1.25, 1.75, 2.75, 3, 9, 0.0367, 0.1, 0.25]
        calls = [["nearestPosition", [v, list(core.POINTER_POSITIONS)]] for v in values]
        calls += [["nearestPosition", [v, list(core.SCROLL_POSITIONS)]] for v in values]
        got = self.js(*calls)
        want = [core.nearest_position(v) for v in values]
        want += [core.nearest_position(v, core.SCROLL_POSITIONS) for v in values]
        self.assertEqual(got, want)

    def test_position_value_clamps(self):
        got = self.js(*[["positionValue", [p, list(core.POINTER_POSITIONS)]] for p in (-3, 0, 4, 9, 20)])
        self.assertEqual(got, [core.position_value(p) for p in (-3, 0, 4, 9, 20)])

    def test_format_number_matches(self):
        values = [1.5, 0.3125, 47.0, 0.0, 1.0, 0.0735, 2.2, 0.6875, 1e-7, 15.875, 160.0]
        got = self.js(*[["formatNumber", [v]] for v in values])
        self.assertEqual(got, [core.format_number(float(v)) for v in values])

    def test_parse_header_matches(self):
        texts = [HEADER, "", "motion_step=0.5\n", "# hand written\nmotion_step=0.3\n",
                 HEADER.replace("generated by", "made by")]
        got = self.js(*[["parseHeader", [t]] for t in texts])
        self.assertEqual(got, [core.parse_header(t) for t in texts])

    def test_set_args_match(self):
        params = json.dumps({"pointer_setting": 1.0, "scroll_setting": 0.1838})
        defaults, = self.js(["accelDefaults", [params]])
        self.assertEqual(defaults, core.accel_defaults(json.loads(params)))
        conf = core.parse_header(HEADER)
        values = core.accel_values(conf, core.accel_defaults())
        values["pointerSetting"], values["scrollSetting"] = 0.6875, 0.0735
        got, = self.js(["buildSetArgs", [values]])
        self.assertEqual(got, ["set"] + core.build_set_args(values))
        merged, = self.js(["accelValues", [conf, core.ACCEL_DEFAULTS]])
        self.assertEqual(merged, core.accel_values(conf, core.ACCEL_DEFAULTS))
        missing, = self.js(["accelValues", [None, core.ACCEL_DEFAULTS]])
        self.assertEqual(missing, core.ACCEL_DEFAULTS)

    def test_set_switch_keeps_other_keys(self):
        text = '{\n    "acceleration": 1.5,\n    "momentum": true,\n    "momentumFastDecay": 0.97,\n    "logLevel": "info"\n}\n'
        on, off, new, empty = self.js(["setSwitch", [text, "momentum", False]],
                                      ["setSwitch", [text, "threeFingerDrag", False]],
                                      ["setSwitch", ["{}", "momentum", True]],
                                      ["setSwitch", ["", "threeFingerDrag", True]])
        self.assertTrue(on["ok"])
        self.assertEqual(json.loads(on["text"]), core.merge_momentum(json.loads(text), False))
        self.assertEqual(list(json.loads(on["text"])), ["acceleration", "momentum", "momentumFastDecay", "logLevel"])
        self.assertEqual(on["text"], core.dump_json(core.merge_momentum(json.loads(text), False)))
        self.assertEqual(list(json.loads(off["text"]))[-1], "threeFingerDrag")
        self.assertEqual(json.loads(new["text"]), {"momentum": True})
        self.assertEqual(json.loads(empty["text"]), {"threeFingerDrag": True})

    def test_bad_daemon_json_is_not_written(self):
        bad, arr = self.js(["setSwitch", ["{nope", "momentum", False]],
                           ["setSwitch", ["[1, 2]", "momentum", False]])
        self.assertFalse(bad["ok"])
        self.assertFalse(arr["ok"])
        self.assertEqual(bad["text"], "")

    def test_switch_value_defaults(self):
        got = self.js(["switchValue", [{"momentum": False}, "momentum"]],
                      ["switchValue", [{"momentum": "no"}, "momentum"]],
                      ["switchValue", [{}, "threeFingerDrag"]])
        self.assertEqual(got, [core.momentum_enabled({"momentum": False}),
                               core.momentum_enabled({"momentum": "no"}),
                               core.drag_enabled({})])


if __name__ == "__main__":
    unittest.main()
