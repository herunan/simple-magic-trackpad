class Paths(unittest.TestCase):
    def test_config_dir_override(self):
        self.assertEqual(core.config_dir({"MAC_TRACKPAD_CONFIG_DIR": "/x/y", "HOME": "/h"}), "/x/y")

    def test_config_dir_xdg_and_home(self):
        self.assertEqual(core.config_dir({"XDG_CONFIG_HOME": "/c", "HOME": "/h"}), "/c/mac-trackpad")
        self.assertEqual(core.config_dir({"HOME": "/h"}), "/h/.config/mac-trackpad")

    def test_accel_env_points_xdg_at_override(self):
        env, err = core.accel_env({"MAC_TRACKPAD_CONFIG_DIR": "/tmp/t/mac-trackpad", "HOME": "/h"})
        self.assertIsNone(err)
        self.assertEqual(env["XDG_CONFIG_HOME"], "/tmp/t")

    def test_accel_env_rejects_other_names(self):
        _, err = core.accel_env({"MAC_TRACKPAD_CONFIG_DIR": "/tmp/t/other", "HOME": "/h"})
        self.assertIsNotNone(err)

    def test_accel_env_untouched_without_override(self):
        env, err = core.accel_env({"HOME": "/h", "XDG_CONFIG_HOME": "/c"})
        self.assertIsNone(err)
        self.assertEqual(env["XDG_CONFIG_HOME"], "/c")

    def test_find_curves_script_repo_relative(self):
        self.assertEqual(core.find_curves_script(APP, {"HOME": "/nonexistent"}), CURVES)

    def test_find_curves_script_env_first(self):
        with tempfile.NamedTemporaryFile(suffix=".py") as f:
            self.assertEqual(core.find_curves_script("/nowhere/app", {"MAC_TRACKPAD_CURVES": f.name,
                                                                      "HOME": "/nonexistent"}), f.name)

    def test_find_curves_script_data_dir(self):
        with tempfile.TemporaryDirectory() as d:
            os.makedirs(os.path.join(d, "mac-trackpad"))
            path = os.path.join(d, "mac-trackpad", "mac_curves.py")
            open(path, "w").close()
            self.assertEqual(core.find_curves_script("/nowhere/app", {"XDG_DATA_HOME": d, "HOME": "/nonexistent"}), path)
        with tempfile.TemporaryDirectory() as h:
            path = os.path.join(h, ".local", "share", "mac-trackpad", "mac_curves.py")
            os.makedirs(os.path.dirname(path))
            open(path, "w").close()
            self.assertEqual(core.find_curves_script("/nowhere/app", {"HOME": h}), path)

    def test_data_dir(self):
        self.assertEqual(core.data_dir({"XDG_DATA_HOME": "/d", "HOME": "/h"}), "/d/mac-trackpad")
        self.assertEqual(core.data_dir({"HOME": "/h"}), "/h/.local/share/mac-trackpad")

    def test_curves_supported(self):
        for desktop in ("KDE", "kde", "KDE:GNOME", "ubuntu:KDE", "X-Cinnamon:kde"):
            self.assertTrue(core.curves_supported({"XDG_CURRENT_DESKTOP": desktop}), desktop)
        for desktop in ("Hyprland", "hyprland", "HYPRLAND", "Hyprland:Omarchy"):
            self.assertTrue(core.curves_supported({"XDG_CURRENT_DESKTOP": desktop}), desktop)
        for desktop in ("GNOME", "ubuntu:GNOME", "XFCE", "", "KDEish", "Budgie:GNOME", "Hypr"):
            self.assertFalse(core.curves_supported({"XDG_CURRENT_DESKTOP": desktop}), desktop)
        self.assertFalse(core.curves_supported({}))
        # a Hyprland session is enough even with another or no desktop name
        self.assertTrue(core.curves_supported({"HYPRLAND_INSTANCE_SIGNATURE": "abc"}))
        self.assertTrue(core.curves_supported({"HYPRLAND_INSTANCE_SIGNATURE": "abc",
                                               "XDG_CURRENT_DESKTOP": "GNOME"}))
        self.assertFalse(core.curves_supported({"HYPRLAND_INSTANCE_SIGNATURE": ""}))

    def test_is_kde_and_is_hyprland(self):
        self.assertTrue(core.is_kde({"XDG_CURRENT_DESKTOP": "KDE"}))
        self.assertFalse(core.is_kde({"XDG_CURRENT_DESKTOP": "Hyprland"}))
        self.assertFalse(core.is_kde({"HYPRLAND_INSTANCE_SIGNATURE": "abc"}))
        self.assertTrue(core.is_hyprland({"XDG_CURRENT_DESKTOP": "Hyprland"}))
        self.assertTrue(core.is_hyprland({"HYPRLAND_INSTANCE_SIGNATURE": "abc"}))
        self.assertFalse(core.is_hyprland({"XDG_CURRENT_DESKTOP": "KDE"}))
        self.assertFalse(core.is_hyprland({}))

    def test_find_curves_script_missing(self):
        self.assertIsNone(core.find_curves_script("/nowhere/app", {"HOME": "/nonexistent"}))


class DaemonJson(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.path = os.path.join(self.tmp.name, "daemon.json")

    def tearDown(self):
        self.tmp.cleanup()

    def write(self, data):
        with open(self.path, "w") as f:
            json.dump(data, f, indent=4)

    def test_read_missing_is_empty(self):
        self.assertEqual(core.read_json(self.path), {})

    def test_read_rejects_non_object(self):
        with open(self.path, "w") as f:
            f.write("[1, 2]")
        with self.assertRaises(ValueError):
            core.read_json(self.path)

    def test_drag_enabled_default_and_type(self):
        self.assertIs(core.drag_enabled({}), False)
        self.assertIs(core.drag_enabled({"threeFingerDrag": False}), False)
        self.assertIs(core.drag_enabled({"threeFingerDrag": "no"}), False)

    def test_momentum_enabled_default_and_type(self):
        self.assertIs(core.momentum_enabled({}), True)
        self.assertIs(core.momentum_enabled({"momentum": False}), False)
        self.assertIs(core.momentum_enabled({"momentum": "no"}), True)

    def test_merge_sets_only_momentum(self):
        data = {"acceleration": 1.0, "momentumDecay": 400, "logLevel": "info",
                "momentum": True, "momentumTailDecay": 0.9, "momentumStopHold": 160,
                "zzz": [1, {"a": 2}]}
        out = core.merge_momentum(data, False)
        self.assertEqual(out, dict(data, momentum=False))
        self.assertEqual(list(out), list(data), "key order kept")
        self.assertIs(data["momentum"], True, "input must not be modified")

    def test_merge_appends_missing_key(self):
        self.assertEqual(list(core.merge_momentum({"a": 1}, True)), ["a", "momentum"])

    def test_write_momentum_writes_only_that_key(self):
        before = {"acceleration": 1.0, "dragEndDelay": 0, "momentum": True,
                  "momentumDecay": 400, "momentumFastDecay": 0.98,
                  "momentumTailDecay": 0.9, "momentumStopHold": 160,
                  "nested": {"a": [1, 2]}}
        self.write(before)
        os.chmod(self.path, 0o600)
        core.write_momentum(self.path, False)
        with open(self.path) as f:
            text = f.read()
        self.assertTrue(text.endswith("}\n"))
        self.assertIn('\n    "acceleration": 1.0,\n', text)  # 4-space indent
        data = json.loads(text)
        self.assertEqual(data, dict(before, momentum=False))
        self.assertEqual(list(data), list(before))
        self.assertEqual(stat.S_IMODE(os.stat(self.path).st_mode), 0o600)
        self.assertEqual(os.listdir(self.tmp.name), ["daemon.json"], "temp file left behind")

    def test_write_creates_missing_file_and_dir(self):
        path = os.path.join(self.tmp.name, "sub", "daemon.json")
        core.write_momentum(path, True)
        self.assertEqual(core.read_json(path), {"momentum": True})

    def test_atomic_write_replaces_inode(self):
        self.write({"a": 1})
        before = os.stat(self.path).st_ino
        core.atomic_write(self.path, "{}\n")
        self.assertNotEqual(os.stat(self.path).st_ino, before)


class AccelConf(unittest.TestCase):
    def test_parse_header(self):
        self.assertEqual(core.parse_header(HEADER), {
            "pointerSetting": 1.5, "scrollSetting": 0.3125, "res": 47.0,
            "pointerGain": 1.2, "scrollGain": 0.8, "kwinScrollFactor": 1.4, "step": 0.25})

    def test_parse_header_ignores_other_comments(self):
        self.assertEqual(core.parse_header("# hand written, pointer gain 9\nmotion_step=0.5\n"),
                         {"step": 0.5})

    def test_read_missing(self):
        self.assertIsNone(core.read_accel_conf("/nonexistent/accel.conf"))

    def test_read_accel_conf_file(self):
        with tempfile.TemporaryDirectory() as d:
            p = os.path.join(d, "accel.conf")
            with open(p, "w") as f:
                f.write(HEADER)
            self.assertEqual(core.read_accel_conf(p)["pointerGain"], 1.2)

    def test_format_number(self):
        self.assertEqual(core.format_number(15.875), "15.875")
        self.assertEqual(core.format_number(1.0), "1")
        self.assertEqual(core.format_number(160), "160")
        self.assertEqual(core.format_number(0.1 + 0.2), "0.3")
        self.assertEqual(core.format_number(0.4412), "0.4412")
        self.assertEqual(core.format_number(True), "true")

    def test_hidden_values_passed_through(self):
        values = core.accel_values(core.parse_header(HEADER))
        values["pointerSetting"] = 2.0  # what the user picked
        self.assertEqual(core.build_set_args(values), [
            "--pointer-setting", "2", "--pointer-gain", "1.2",
            "--scroll-setting", "0.3125", "--scroll-gain", "0.8",
            "--kwin-scroll-factor", "1.4", "--res", "47", "--step", "0.25"])

    def test_hidden_values_unchanged_when_scroll_moves(self):
        conf = {"pointerSetting": 1.23, "scrollSetting": 0.4412, "res": 52.5,
                "pointerGain": 1.75, "scrollGain": 0.6, "kwinScrollFactor": 2.2, "step": 0.3}
        values = core.accel_values(conf)
        values["scrollSetting"] = 1.2346
        args = core.build_set_args(values)
        opts = dict(zip(args[::2], args[1::2]))
        self.assertEqual(opts, {
            "--pointer-setting": "1.23", "--pointer-gain": "1.75",
            "--scroll-setting": "1.2346", "--scroll-gain": "0.6",
            "--kwin-scroll-factor": "2.2", "--res": "52.5", "--step": "0.3"})

    def test_missing_accel_conf_uses_defaults(self):
        values = core.accel_values(None)
        self.assertEqual(values, core.ACCEL_DEFAULTS)
        self.assertEqual(core.build_set_args(values), [
            "--pointer-setting", "1.5", "--pointer-gain", "1",
            "--scroll-setting", "0.3125", "--scroll-gain", "1",
            "--kwin-scroll-factor", "1.4", "--res", "47", "--step", "0.25"])

    def test_partial_header_fills_in_defaults(self):
        values = core.accel_values({"res": 50.0, "pointerGain": 1.1})
        self.assertEqual(values["res"], 50.0)
        self.assertEqual(values["pointerGain"], 1.1)
        self.assertEqual(values["step"], 0.25)

    def test_accel_defaults_from_params(self):
        d = core.accel_defaults({"pointer_setting": 2.0, "scroll_setting": 0.5})
        self.assertEqual((d["pointerSetting"], d["scrollSetting"]), (2.0, 0.5))
        self.assertEqual(core.accel_defaults({"pointer_setting": "x"}), core.ACCEL_DEFAULTS)

    @unittest.skipUnless(os.path.isfile(CURVES), "accel/mac_curves.py not in the repo")
    def test_header_round_trip_through_mac_curves(self):
        import subprocess
        values = dict(core.ACCEL_DEFAULTS, pointerSetting=2.25, scrollSetting=0.4412,
                      scrollGain=0.85, kwinScrollFactor=1.1, step=0.3)
        out = subprocess.run([sys.executable, CURVES] + core.build_set_args(values),
                             capture_output=True, text=True, check=True).stdout
        self.assertEqual(core.accel_values(core.parse_header(out)), values)

    @unittest.skipUnless(os.path.isfile(CURVES), "accel/mac_curves.py not in the repo")
    def test_defaults_from_params_file(self):
        params = core.load_params(CURVES)
        self.assertEqual(params["pointer_setting"], core.DEFAULT_POINTER_SETTING)
        self.assertEqual(params["scroll_setting"], core.DEFAULT_SCROLL_SETTING)


class Positions(unittest.TestCase):
    VALUES = [0, 0.125, 0.5, 0.6875, 0.875, 1, 1.5, 2, 2.5, 3]

    def test_ten_positions_map_to_macos_values(self):
        self.assertEqual(list(core.POINTER_POSITIONS), self.VALUES)
        for i, v in enumerate(self.VALUES):
            self.assertEqual(core.position_value(i), v)

    def test_listed_values_map_back_to_their_position(self):
        for i, v in enumerate(self.VALUES):
            self.assertEqual(core.nearest_position(v), i)

    def test_off_list_values_show_nearest_position(self):
        self.assertEqual(core.nearest_position(1.2), 5)    # 1 (0.2) vs 1.5 (0.3)
        self.assertEqual(core.nearest_position(1.3), 6)    # 1.5 (0.2) vs 1 (0.3)
        self.assertEqual(core.nearest_position(0.3), 1)    # 0.125 (0.175) vs 0.5 (0.2)
        self.assertEqual(core.nearest_position(0.9), 4)
        self.assertEqual(core.nearest_position(2.9), 9)
        self.assertEqual(core.nearest_position(0.01), 0)

    def test_out_of_range_values(self):
        self.assertEqual(core.nearest_position(-4), 0)
        self.assertEqual(core.nearest_position(99), 9)
        self.assertEqual(core.position_value(-1), 0)
        self.assertEqual(core.position_value(42), 3)

    def test_scroll_range_constant(self):
        speeds = core.SCROLL_POSITIONS
        self.assertEqual(len(speeds), 8)
        for i, v in enumerate(speeds):
            self.assertEqual(core.nearest_position(v, speeds), i)
            self.assertEqual(core.position_value(i, speeds), v)
        self.assertEqual(core.nearest_position(0.5881999999999999, speeds), 6)
        self.assertEqual(core.position_value(42, speeds), 1.0)


