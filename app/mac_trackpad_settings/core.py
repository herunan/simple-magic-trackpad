"""Pure logic for the Mac Trackpad settings app (no Qt imports here).

The app offers the options macOS offers: tracking speed, scroll speed, inertia
(momentum) scrolling and three-finger drag.

- daemon.json: read, set only the changed switch's key, write atomically (tmp + rename).
- accel.conf: parse the "# generated by mac_curves.py: ..." header, so values the
  app doesn't show (gains, resolution, ...) are passed through unchanged.
- mac-trackpad-accel: build the mac_curves.py options for `set`.
"""
import json
import os
import re
import tempfile


# ---------------------------------------------------------------- settings

MOMENTUM_SWITCH_KEY = "momentum"
MOMENTUM_SWITCH_DEFAULT = True
DRAG_SWITCH_KEY = "threeFingerDrag"
DRAG_SWITCH_DEFAULT = False

# The tracking speeds macOS has curves for (System Settings > Trackpad),
# one slider position each.
POINTER_POSITIONS = (0.0, 0.125, 0.5, 0.6875, 0.875, 1.0, 1.5, 2.0, 2.5, 3.0)

# The scroll speeds of the macOS slider (Accessibility > Pointer Control >
# Trackpad Options), read off com.apple.trackpad.scrolling on macOS 26.
SCROLL_POSITIONS = (0.0, 0.0735, 0.1265, 0.1838, 0.3125, 0.4412, 0.5882, 1.0)

# Defaults as in mac_curves.py's argparse; the two settings default to
# whatever mac-params.json says (see load_params()).
DEFAULT_POINTER_SETTING = 1.5
DEFAULT_SCROLL_SETTING = 0.3125

# accel.conf header values -> mac_curves.py option, in the order passed to
# `mac-trackpad-accel set`. The two settings are the ones the app shows; the
# rest are hidden and carried over from accel.conf.
ACCEL_OPTIONS = (
    ("pointerSetting", "--pointer-setting"),
    ("pointerGain", "--pointer-gain"),
    ("scrollSetting", "--scroll-setting"),
    ("scrollGain", "--scroll-gain"),
    ("kwinScrollFactor", "--kwin-scroll-factor"),
    ("res", "--res"),
    ("step", "--step"),
)
ACCEL_DEFAULTS = {
    "pointerSetting": DEFAULT_POINTER_SETTING,
    "pointerGain": 1.0,
    "scrollSetting": DEFAULT_SCROLL_SETTING,
    "scrollGain": 1.0,
    "kwinScrollFactor": 1.4,
    "res": 47.0,
    "step": 0.25,
}


def nearest_position(value, positions=POINTER_POSITIONS):
    """Slider position (index into positions) whose value is closest to value;
    ties go to the lower position."""
    return min(range(len(positions)), key=lambda i: abs(positions[i] - value))


def position_value(position, positions=POINTER_POSITIONS):
    """The speed of a slider position (clamped to the valid range)."""
    return positions[min(max(int(position), 0), len(positions) - 1)]


def format_number(v):
    """Short decimal text for a value: 1.5, 0.3125, 160, 15.875."""
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    s = "%.6f" % float(v)
    s = s.rstrip("0").rstrip(".")
    return "0" if s in ("", "-0") else s


# ---------------------------------------------------------------- paths


def config_dir(env=None):
    env = os.environ if env is None else env
    if env.get("MAC_TRACKPAD_CONFIG_DIR"):
        return env["MAC_TRACKPAD_CONFIG_DIR"]
    base = env.get("XDG_CONFIG_HOME") or os.path.join(env.get("HOME", os.path.expanduser("~")), ".config")
    return os.path.join(base, "mac-trackpad")


def accel_env(env=None):
    """Environment for running mac-trackpad-accel so it writes accel.conf into
    config_dir(). Returns (env dict, error or None)."""
    env = dict(os.environ if env is None else env)
    override = env.get("MAC_TRACKPAD_CONFIG_DIR")
    if override:
        d = os.path.abspath(override)
        if os.path.basename(d) != "mac-trackpad":
            return env, ("MAC_TRACKPAD_CONFIG_DIR must end in /mac-trackpad for "
                         "mac-trackpad-accel to write accel.conf there")
        env["XDG_CONFIG_HOME"] = os.path.dirname(d)
    return env, None


def data_dir(env=None):
    """Where accel/install.sh puts mac_curves.py and mac-params.json:
    ${XDG_DATA_HOME:-$HOME/.local/share}/mac-trackpad."""
    env = os.environ if env is None else env
    base = env.get("XDG_DATA_HOME") or os.path.join(env.get("HOME", os.path.expanduser("~")), ".local", "share")
    return os.path.join(base, "mac-trackpad")


def find_curves_script(app_dir, env=None):
    """Where accel/mac_curves.py is: $MAC_TRACKPAD_CURVES, next to this app in
    the repo, or the data directory accel/install.sh fills (data_dir()). None
    if not found."""
    env = os.environ if env is None else env
    candidates = []
    if env.get("MAC_TRACKPAD_CURVES"):
        candidates.append(env["MAC_TRACKPAD_CURVES"])
    candidates.append(os.path.join(os.path.dirname(os.path.abspath(app_dir)), "accel", "mac_curves.py"))
    candidates.append(os.path.join(data_dir(env), "mac_curves.py"))
    for c in candidates:
        if os.path.isfile(c):
            return c
    return None


def is_kde(env=None):
    """True on KDE Plasma. XDG_CURRENT_DESKTOP is a colon-separated list;
    matched case-insensitively."""
    env = os.environ if env is None else env
    return "KDE" in env.get("XDG_CURRENT_DESKTOP", "").upper().split(":")


def is_hyprland(env=None):
    """True on Hyprland: HYPRLAND_INSTANCE_SIGNATURE is set, or
    XDG_CURRENT_DESKTOP contains Hyprland (any case). Same test as
    mac-trackpad-accel's."""
    env = os.environ if env is None else env
    return bool(env.get("HYPRLAND_INSTANCE_SIGNATURE")) or "HYPRLAND" in env.get("XDG_CURRENT_DESKTOP", "").upper()


def curves_supported(env=None):
    """True where mac-trackpad-accel can apply the tracking/scroll curves: KDE
    (through the KWin shim) and Hyprland (through its own device config)."""
    return is_kde(env) or is_hyprland(env)


def load_params(curves_path):
    with open(os.path.join(os.path.dirname(curves_path), "mac-params.json")) as f:
        return json.load(f)


def find_accel_tool(env=None):
    env = os.environ if env is None else env
    if env.get("MAC_TRACKPAD_ACCEL"):
        return env["MAC_TRACKPAD_ACCEL"]
    home = env.get("HOME", os.path.expanduser("~"))
    local = os.path.join(home, ".local", "bin", "mac-trackpad-accel")
    if os.path.isfile(local):
        return local
    import shutil
    return shutil.which("mac-trackpad-accel", path=env.get("PATH")) or local


# ---------------------------------------------------------------- daemon.json


def read_json(path):
    """The daemon config as a dict ({} if the file doesn't exist)."""
    try:
        with open(path) as f:
            text = f.read()
    except FileNotFoundError:
        return {}
    data = json.loads(text) if text.strip() else {}
    if not isinstance(data, dict):
        raise ValueError(f"{path}: top level is not a JSON object")
    return data


def momentum_enabled(data):
    """The momentum switch from a daemon config dict (default where missing or
    not a boolean)."""
    sw = data.get(MOMENTUM_SWITCH_KEY, MOMENTUM_SWITCH_DEFAULT)
    return sw if isinstance(sw, bool) else MOMENTUM_SWITCH_DEFAULT


def drag_enabled(data):
    """The three-finger drag switch from a daemon config dict (default where
    missing or not a boolean)."""
    sw = data.get(DRAG_SWITCH_KEY, DRAG_SWITCH_DEFAULT)
    return sw if isinstance(sw, bool) else DRAG_SWITCH_DEFAULT


def merge_momentum(data, enabled):
    """A copy of data with only the momentum key set (same key order, appended
    if new). Every other key, momentum* tuning keys included, is untouched."""
    out = dict(data)
    out[MOMENTUM_SWITCH_KEY] = bool(enabled)
    return out


def dump_json(data):
    return json.dumps(data, indent=4) + "\n"


def atomic_write(path, text):
    """Write text to path via a temp file in the same directory + rename, so
    a reader (the daemon's hot reload) never sees a half-written file."""
    d = os.path.dirname(os.path.abspath(path))
    os.makedirs(d, exist_ok=True)
    try:
        mode = os.stat(path).st_mode & 0o7777
    except FileNotFoundError:
        mode = 0o644
    fd, tmp = tempfile.mkstemp(prefix="." + os.path.basename(path) + ".", suffix=".tmp", dir=d)
    try:
        with os.fdopen(fd, "w") as f:
            f.write(text)
            f.flush()
            os.fsync(f.fileno())
        os.chmod(tmp, mode)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except FileNotFoundError:
            pass
        raise


def write_momentum(path, enabled):
    """Re-read daemon.json, set only the momentum key, write it atomically.
    Returns the written dict."""
    data = merge_momentum(read_json(path), enabled)
    atomic_write(path, dump_json(data))
    return data


def write_drag(path, enabled):
    """Re-read daemon.json, set only the three-finger drag key, write it
    atomically. Returns the written dict."""
    data = dict(read_json(path))
    data[DRAG_SWITCH_KEY] = bool(enabled)
    atomic_write(path, dump_json(data))
    return data


# ---------------------------------------------------------------- accel.conf

_NUM = r"([-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?)"
_HEADER_FIELDS = {
    "pointerSetting": r"\bpointer setting " + _NUM,
    "scrollSetting": r"\bscroll setting " + _NUM,
    "res": r"\bres " + _NUM + r" units/mm",
    "pointerGain": r"\bpointer gain " + _NUM,
    "scrollGain": r"\bscroll gain " + _NUM,
    "kwinScrollFactor": r"\bkwin scroll factor " + _NUM,
}


def parse_header(text):
    """Curve values from accel.conf's leading comment lines (plus step from
    motion_step=). Only the fields found are returned."""
    comments = []
    out = {}
    for line in text.splitlines():
        s = line.strip()
        if s.startswith("#"):
            comments.append(s.lstrip("#").strip())
        elif s.startswith("motion_step="):
            try:
                out["step"] = float(s.split("=", 1)[1])
            except ValueError:
                pass
    joined = " ".join(comments)
    if "generated by mac_curves.py" not in joined:
        return out
    for key, pat in _HEADER_FIELDS.items():
        m = re.search(pat, joined)
        if m:
            out[key] = float(m.group(1))
    return out


def read_accel_conf(path):
    """parse_header() of the file, or None if it doesn't exist."""
    try:
        with open(path) as f:
            return parse_header(f.read())
    except FileNotFoundError:
        return None


def accel_defaults(params=None):
    """ACCEL_DEFAULTS, with the two settings from mac-params.json (params) when
    given."""
    out = dict(ACCEL_DEFAULTS)
    for key, name in (("pointerSetting", "pointer_setting"), ("scrollSetting", "scroll_setting")):
        try:
            out[key] = float((params or {})[name])
        except (KeyError, TypeError, ValueError):
            pass
    return out


def accel_values(conf, defaults=ACCEL_DEFAULTS):
    """Every accel value: the ones found in the accel.conf header (conf, may be
    None for a missing file), the rest from defaults."""
    out = dict(defaults)
    out.update({k: v for k, v in (conf or {}).items() if k in defaults})
    return out


def build_set_args(values):
    """mac_curves.py options for `mac-trackpad-accel set`, every value explicit.
    values: accel_values() with pointerSetting/scrollSetting as chosen."""
    args = []
    for key, option in ACCEL_OPTIONS:
        args += [option, format_number(float(values[key]))]
    return args
